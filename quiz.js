// Helper to flatten 4-line puzzle object into a 52-character array
function quizItemTo52Array(puzzle) {
    if (!puzzle) return new Array(52).fill("");
    if (Array.isArray(puzzle) && puzzle.length === 52) return puzzle;
    
    let letters = [];
    // Line 1: 12 cells
    for (let i = 0; i < 12; i++) {
        letters.push((puzzle.line1 && puzzle.line1[i]) ? puzzle.line1[i] : "");
    }
    // Line 2: 14 cells
    for (let i = 0; i < 14; i++) {
        letters.push((puzzle.line2 && puzzle.line2[i]) ? puzzle.line2[i] : "");
    }
    // Line 3: 14 cells
    for (let i = 0; i < 14; i++) {
        letters.push((puzzle.line3 && puzzle.line3[i]) ? puzzle.line3[i] : "");
    }
    // Line 4: 12 cells
    for (let i = 0; i < 12; i++) {
        letters.push((puzzle.line4 && puzzle.line4[i]) ? puzzle.line4[i] : "");
    }
    return letters;
}

